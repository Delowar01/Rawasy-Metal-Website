/**
 * Regenerates src/server/security/common-passwords.generated.ts, the bundled list of common and breached passwords the
 * admin refuses (A1-SECURITY-RBAC §3.2). Development only: run it by hand when the list should be refreshed; nothing in
 * the website runs it.
 *
 *   node scripts/generate-common-passwords.mjs
 *
 * Source: SecLists (https://github.com/danielmiessler/SecLists, MIT licence, Copyright (c) 2018 Daniel Miessler), files
 * Passwords/Common-Credentials/xato-net-10-million-passwords-100000.txt and Pwdb_top-100000.txt. Only entries of 12 to
 * 128 characters are kept (shorter ones already fail the length rule), normalized like the admin normalizes passwords
 * (NFKC, lower case), sorted and de-duplicated.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const BASE = "https://raw.githubusercontent.com/danielmiessler/SecLists/master/Passwords/Common-Credentials/";
const FILES = ["xato-net-10-million-passwords-100000.txt", "Pwdb_top-100000.txt"];
const OUT = resolve(import.meta.dirname, "../src/server/security/common-passwords.generated.ts");

const words = new Set();
for (const file of FILES) {
  const response = await fetch(BASE + file);
  if (!response.ok) throw new Error(`${file}: HTTP ${response.status}`);
  for (const line of (await response.text()).split(/\r?\n/)) {
    const word = line.normalize("NFKC").toLowerCase();
    const length = [...word].length;
    if (length >= 12 && length <= 128) words.add(word);
  }
}
const list = [...words].sort();
const body = list.map((w) => JSON.stringify(w)).join(",\n  ");
writeFileSync(
  OUT,
  `/**
 * Generated by scripts/generate-common-passwords.mjs — do not edit by hand.
 *
 * Common and breached passwords of 12 characters or more, normalized (NFKC, lower case): ${list.length} entries.
 * Source: SecLists, ${FILES.join(" and ")} (https://github.com/danielmiessler/SecLists).
 * MIT License. Copyright (c) 2018 Daniel Miessler.
 */
export const COMMON_PASSWORDS: readonly string[] = [
  ${body},
];
`,
);
console.log(`Wrote ${list.length} entries to ${OUT}`);
