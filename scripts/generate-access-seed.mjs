/**
 * Writes the seed migrations from the code registries. Development only; nothing in the website runs it.
 *
 * - drizzle/0001_seed_access_control.sql — the seed data of A2 (locales, roles, permissions and the role matrix) from
 *   src/server/policy/registry.ts: every permission without a `since` phase, and the grants of those permissions.
 * - drizzle/0003_seed_core_cms.sql — the seed data of A3: the collections' orderings (src/server/cms/registry.ts) and
 *   the permissions the registry marks `since: "A3"` (`projects.add_flags`) with their grants.
 * - drizzle/0007_seed_site_controls.sql — the seed data of A6 (src/server/site/registry.ts): the singletons 'site' and
 *   'theme', the design's four menu slots and every interface-text key with its group, help and maximum length. No
 *   content: the company facts, menu items and interface text are copied from today's website by the admin's set-up
 *   actions (A6 report, item 3), so this file never depends on the content files.
 * - drizzle/0009_seed_forms_enquiries.sql — the seed data of A7 (src/server/forms/registry.ts): the quote form's root row
 *   (today's handoff delivery, the anti-spam and attachment defaults, no retention period). No field or text: the admin's
 *   set-up copies today's form into it (A7 report, item 4).
 * - drizzle/0011_seed_publishing.sql — the seed data of A8 (src/server/publishing/registry.ts): the cache generation's
 *   single row (the first epoch, generation 0). Nothing is published by a migration.
 *
 *   node scripts/generate-access-seed.mjs            write the files (refused once a file holds other SQL: see below)
 *   node scripts/generate-access-seed.mjs --check    exit 1 if a file differs from what the registries give
 *
 * A migration never changes after it has been applied anywhere: a later change to the roles, the matrix or the
 * orderings is a new migration. `--check` (run by `npm run db:check` and the integration tests) proves the committed
 * files still match the registries — together, the database the migrations build holds exactly the registry.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

// Node warns that the registries are TypeScript in a package without "type"; that warning only (others print).
const warn = process.rawListeners("warning");
process.removeAllListeners("warning");
process.on("warning", (w) => w.code === "MODULE_TYPELESS_PACKAGE_JSON" || warn.forEach((listener) => listener(w)));

const { PERMISSIONS, ROLES, ROLE_PERMISSIONS } = await import("../src/server/policy/registry.ts");
const { ORDERINGS } = await import("../src/server/cms/registry.ts");
const { MENU_SLOTS, UI_STRINGS, COUNTRY_CODE } = await import("../src/server/site/registry.ts");
const { DEFAULT_ATTACHMENT_EXTENSIONS, FORM_IDS, FORM_LIMITS } = await import("../src/server/forms/registry.ts");
const { INITIAL_CACHE_EPOCH } = await import("../src/server/publishing/registry.ts");

const BREAK = "\n--> statement-breakpoint\n";

const NOW = { raw: "UTC_TIMESTAMP(3)" };
const q = (value) => {
  if (value === NOW) return NOW.raw;
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "1" : "0";
  if (value === null) return "NULL";
  if (/[\\\u0000-\u001f]/.test(value)) throw new Error(`Unexpected character in ${JSON.stringify(value)}`);
  return `'${value.replace(/'/g, "''")}'`;
};
const rows = (values) => values.map((row) => `  (${row.map(q).join(", ")})`).join(",\n");

const LOCALES = [
  // code, name, native name, direction, <html lang>, Open Graph locale, default, enabled, required, order
  ["en", "English", "English", "ltr", "en", "en_US", true, true, true, 1],
  ["ar", "Arabic", "عربي", "rtl", "ar-SA", "ar_SA", false, true, true, 2],
];

/** The grants of the given permission keys, role by role, in a stable order. */
const grantsOf = (keys) => ROLES.flatMap((r) => [...ROLE_PERMISSIONS[r.key]].filter((p) => keys.has(p)).sort().map((p) => [r.key, p]));

const A2_PERMISSIONS = PERMISSIONS.filter((p) => !p.since);
const A3_PERMISSIONS = PERMISSIONS.filter((p) => p.since === "A3");

const accessSeed =
  [
    `-- Seed data of A2 (A1-DATABASE-SCHEMA §10.7), generated by scripts/generate-access-seed.mjs from
-- src/server/policy/registry.ts. Reviewed; never edited after it has been applied (a change is a new migration).
INSERT INTO \`locales\` (\`code\`, \`name\`, \`native_name\`, \`direction\`, \`html_lang\`, \`og_locale\`, \`is_default\`, \`is_enabled\`, \`is_required\`, \`sort_order\`) VALUES
${rows(LOCALES)};`,
    `INSERT INTO \`roles\` (\`key\`, \`name\`, \`description\`, \`rank\`, \`is_system\`, \`created_at\`, \`updated_at\`) VALUES
${rows(ROLES.map((r) => [r.key, r.name, r.description, r.rank, true, NOW, NOW]))};`,
    `INSERT INTO \`permissions\` (\`key\`, \`resource\`, \`action\`, \`description\`, \`is_sensitive\`) VALUES
${rows(A2_PERMISSIONS.map((p) => [p.key, p.resource, p.action, p.description, p.isSensitive]))};`,
    `INSERT INTO \`role_permissions\` (\`role_key\`, \`permission_key\`) VALUES
${rows(grantsOf(new Set(A2_PERMISSIONS.map((p) => p.key))))};`,
  ].join(BREAK) + "\n";

const coreCmsSeed =
  [
    `-- Seed data of A3 (A1-DATABASE-SCHEMA §10.7), generated by scripts/generate-access-seed.mjs from
-- src/server/cms/registry.ts (the collections' orderings, A1 \`entity_orderings\`) and src/server/policy/registry.ts (the
-- permission A3 adds: "Project flags — add", A1-SECURITY-RBAC §5.3). Reviewed; never edited after it has been applied.
INSERT INTO \`entity_orderings\` (\`key\`, \`entity_type\`, \`created_at\`, \`updated_at\`) VALUES
${rows(Object.entries(ORDERINGS).map(([key, type]) => [key, type, NOW, NOW]))};`,
    `INSERT INTO \`permissions\` (\`key\`, \`resource\`, \`action\`, \`description\`, \`is_sensitive\`) VALUES
${rows(A3_PERMISSIONS.map((p) => [p.key, p.resource, p.action, p.description, p.isSensitive]))};`,
    `INSERT INTO \`role_permissions\` (\`role_key\`, \`permission_key\`) VALUES
${rows(grantsOf(new Set(A3_PERMISSIONS.map((p) => p.key))))};`,
  ].join(BREAK) + "\n";

const siteSeed =
  [
    `-- Seed data of A6 (A1-DATABASE-SCHEMA §7, §10.7), generated by scripts/generate-access-seed.mjs from
-- src/server/site/registry.ts: the singletons (site settings 'site', theme 'theme'), the design's menu slots and the
-- interface-text keys. The settings row starts empty (no company fact is written here): the admin's set-up copies
-- today's website into it. Reviewed; never edited after it has been applied (a change is a new migration).
INSERT INTO \`site_settings\` (\`id\`, \`website_url\`, \`email\`, \`country_code\`, \`maps_query\`, \`created_at\`, \`updated_at\`) VALUES
${rows([["site", "", "", COUNTRY_CODE, "", NOW, NOW]])};`,
    `INSERT INTO \`theme_settings\` (\`id\`, \`created_at\`, \`updated_at\`) VALUES
${rows([["theme", NOW, NOW]])};`,
    `INSERT INTO \`menus\` (\`key\`, \`name\`, \`created_at\`, \`updated_at\`) VALUES
${rows(MENU_SLOTS.map((slot) => [slot.key, slot.name, NOW, NOW]))};`,
    `INSERT INTO \`ui_strings\` (\`key\`, \`settings_id\`, \`group_key\`, \`description\`, \`max_length\`) VALUES
${rows(UI_STRINGS.map((s) => [s.key, "site", s.group, s.description, s.maxLength]))};`,
  ].join(BREAK) + "\n";

const formsSeed =
  [
    `-- Seed data of A7 (A1-DATABASE-SCHEMA §7, §10.7), generated by scripts/generate-access-seed.mjs from
-- src/server/forms/registry.ts: the quote form's root row — delivery 'handoff' (today's: nothing is stored), enabled, the
-- honeypot on, today's minimum fill time, the privacy notice (no consent box), no stored attachments (the Owner's
-- decision), today's file limits and no retention period (the Owner's and legal review's decision). No field and no text:
-- the admin's set-up copies today's form into it. Reviewed; never edited after it has been applied (a change is a new
-- migration).
INSERT INTO \`forms\` (\`id\`, \`key\`, \`delivery_mode\`, \`is_enabled\`, \`retention_days\`, \`honeypot_enabled\`, \`min_fill_seconds\`, \`consent_mode\`, \`accept_files\`, \`max_files\`, \`max_file_mb\`, \`accepted_extensions\`, \`created_at\`, \`updated_at\`) VALUES
${rows([[FORM_IDS.quote, "quote", "handoff", true, null, true, FORM_LIMITS.minFillSeconds.today, "notice", false, FORM_LIMITS.maxFiles.today, FORM_LIMITS.maxFileMb.today, DEFAULT_ATTACHMENT_EXTENSIONS, NOW, NOW]])};`,
  ].join(BREAK) + "\n";

const publishingSeed =
  [
    `-- Seed data of A8 (A1-DATABASE-SCHEMA §7, A1-PUBLISHING-VERSIONS §8.2), generated by scripts/generate-access-seed.mjs from
-- src/server/publishing/registry.ts: the cache generation's single row — the first epoch (a database restore replaces it)
-- and generation 0 (every publish takes the next one as its last write). Nothing is published by a migration.
-- Reviewed; never edited after it has been applied (a change is a new migration).
INSERT INTO \`cache_generation\` (\`id\`, \`epoch\`, \`value\`, \`updated_at\`) VALUES
${rows([[1, INITIAL_CACHE_EPOCH, 0, NOW]])};`,
  ].join(BREAK) + "\n";

const FILES = [
  [resolve(import.meta.dirname, "../drizzle/0001_seed_access_control.sql"), accessSeed],
  [resolve(import.meta.dirname, "../drizzle/0003_seed_core_cms.sql"), coreCmsSeed],
  [resolve(import.meta.dirname, "../drizzle/0007_seed_site_controls.sql"), siteSeed],
  [resolve(import.meta.dirname, "../drizzle/0009_seed_forms_enquiries.sql"), formsSeed],
  [resolve(import.meta.dirname, "../drizzle/0011_seed_publishing.sql"), publishingSeed],
];

if (process.argv.includes("--check")) {
  let ok = true;
  for (const [file, sql] of FILES) {
    if (readFileSync(file, "utf8") !== sql) {
      console.error(`${file} does not match the registries (src/server/policy/registry.ts, src/server/cms/registry.ts, src/server/site/registry.ts, src/server/forms/registry.ts, src/server/publishing/registry.ts).`);
      ok = false;
    }
  }
  if (!ok) process.exit(1);
  console.log("Seed migrations match the registries.");
} else {
  for (const [file, sql] of FILES) {
    const current = readFileSync(file, "utf8");
    if (current.trim() && !current.startsWith("-- Custom SQL migration file") && current !== sql) {
      console.error(`Refused: ${file} already holds SQL. Write a new migration for a change.`);
      process.exit(1);
    }
    writeFileSync(file, sql);
    console.log(`Wrote ${file}`);
  }
}
