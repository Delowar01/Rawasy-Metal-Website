/**
 * Writes drizzle/0001_seed_access_control.sql — the seed data of A2 (locales, roles, permissions and the role
 * matrix) — from the code registry src/server/policy/registry.ts. Development only; nothing in the website runs it.
 *
 *   node scripts/generate-access-seed.mjs            write the file (refused once the file holds SQL: see below)
 *   node scripts/generate-access-seed.mjs --check    exit 1 if the file differs from what the registry gives
 *
 * A migration never changes after it has been applied anywhere: a later change to the roles or the matrix is a new
 * migration. `--check` (run by the integration tests) proves the committed file still matches the registry.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

// Node warns that the registry is TypeScript in a package without "type"; that warning only (others print).
const warn = process.rawListeners("warning");
process.removeAllListeners("warning");
process.on("warning", (w) => w.code === "MODULE_TYPELESS_PACKAGE_JSON" || warn.forEach((listener) => listener(w)));

const { PERMISSIONS, ROLES, ROLE_PERMISSIONS } = await import("../src/server/policy/registry.ts");

const OUT = resolve(import.meta.dirname, "../drizzle/0001_seed_access_control.sql");
const BREAK = "\n--> statement-breakpoint\n";

const NOW = { raw: "UTC_TIMESTAMP(3)" };
const q = (value) => {
  if (value === NOW) return NOW.raw;
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "1" : "0";
  if (value === null) return "NULL";
  if (/[\\\u0000-\u001f]/.test(value)) throw new Error(`Unexpected character in ${JSON.stringify(value)}`);
  return `'${value.replace(/'/g, "''")}'`;
};
const rows = (values) => values.map((row) => `  (${row.map(q).join(", ")})`).join(",\n");

const LOCALES = [
  // code, name, native name, direction, <html lang>, Open Graph locale, default, enabled, required, order
  ["en", "English", "English", "ltr", "en", "en_US", true, true, true, 1],
  ["ar", "Arabic", "عربي", "rtl", "ar-SA", "ar_SA", false, true, true, 2],
];

const statements = [
  `-- Seed data of A2 (A1-DATABASE-SCHEMA §10.7), generated by scripts/generate-access-seed.mjs from
-- src/server/policy/registry.ts. Reviewed; never edited after it has been applied (a change is a new migration).
INSERT INTO \`locales\` (\`code\`, \`name\`, \`native_name\`, \`direction\`, \`html_lang\`, \`og_locale\`, \`is_default\`, \`is_enabled\`, \`is_required\`, \`sort_order\`) VALUES
${rows(LOCALES)};`,
  `INSERT INTO \`roles\` (\`key\`, \`name\`, \`description\`, \`rank\`, \`is_system\`, \`created_at\`, \`updated_at\`) VALUES
${rows(ROLES.map((r) => [r.key, r.name, r.description, r.rank, true, NOW, NOW]))};`,
  `INSERT INTO \`permissions\` (\`key\`, \`resource\`, \`action\`, \`description\`, \`is_sensitive\`) VALUES
${rows(PERMISSIONS.map((p) => [p.key, p.resource, p.action, p.description, p.isSensitive]))};`,
  `INSERT INTO \`role_permissions\` (\`role_key\`, \`permission_key\`) VALUES
${rows(ROLES.flatMap((r) => [...ROLE_PERMISSIONS[r.key]].sort().map((p) => [r.key, p])))};`,
];
const sql = statements.join(BREAK) + "\n";

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== sql) {
    console.error("drizzle/0001_seed_access_control.sql does not match src/server/policy/registry.ts.");
    process.exit(1);
  }
  console.log("Seed migration matches the registry.");
} else {
  const current = readFileSync(OUT, "utf8");
  if (current.trim() && !current.startsWith("-- Custom SQL migration file") && current !== sql) {
    console.error("Refused: the seed migration already holds SQL. Write a new migration for a change.");
    process.exit(1);
  }
  writeFileSync(OUT, sql);
  console.log(`Wrote ${OUT}`);
}
