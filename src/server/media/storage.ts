/**
 * The persistent media store (A1-MEDIA-STORAGE §5; A4 brief §9): one root, `RAWASY_DATA_DIR`, outside the application
 * release, outside `public/` and `public_html`, never served directly. Its areas:
 *
 *   $RAWASY_DATA_DIR/media/originals/YYYY/MM/<file-ulid>.<ext>       public-class originals (never served publicly)
 *   $RAWASY_DATA_DIR/media/derived/<media-ulid>/<variant>-<hash8>.webp  generated variants (served when deliverable)
 *   $RAWASY_DATA_DIR/media/private/<media-ulid>/<file-ulid>.<ext>     private items (certificate originals)
 *   $RAWASY_DATA_DIR/tmp/uploads/<upload-ulid>/…                       upload staging
 *
 * Keys are generated by the server from ULIDs and content hashes and checked against a strict grammar; a user's file
 * name never forms a path. Every path is resolved under its area's root and checked again against the real (symlink-
 * free) root before use; files are opened with O_NOFOLLOW. Directories are created 0700 and files 0600.
 *
 * Nothing here runs at build time: the store is opened on first use by a request, a CLI or a test.
 */
import { constants, type ReadStream } from "node:fs";
import { lstat, mkdir, open, readdir, realpath, rename, rm, stat, unlink, type FileHandle } from "node:fs/promises";
import { isAbsolute, join, relative, resolve, sep } from "node:path";
import { randomBytes } from "node:crypto";

export const DATA_DIR_ENV = "RAWASY_DATA_DIR";

export class StorageConfigError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "StorageConfigError";
  }
}

/** A streamed write that was longer than allowed, or not exactly the length it had to be. */
export class StorageSizeError extends Error {
  readonly kind: "too_large" | "wrong_size";
  constructor(kind: "too_large" | "wrong_size") {
    super(kind === "too_large" ? "The data is longer than allowed." : "The data is not the expected length.");
    this.name = "StorageSizeError";
    this.kind = kind;
  }
}

/** A key that does not follow its area's grammar, or a path that leaves its root: never served, never written. */
export class StoragePathError extends Error {
  constructor(message = "Invalid storage key.") {
    super(message);
    this.name = "StoragePathError";
  }
}

export type Area = "originals" | "derived" | "private" | "tmp";

const AREA_DIRS: Record<Area, string> = {
  originals: join("media", "originals"),
  derived: join("media", "derived"),
  private: join("media", "private"),
  tmp: join("tmp", "uploads"),
};

const ULID = "[0-9A-HJKMNP-TV-Z]{26}";
const EXT = "(?:jpg|png|webp|avif|pdf)";
/** The grammar of each area's keys (forward slashes; no dots except before the extension; never `..`). */
export const KEY_GRAMMAR: Record<Area, RegExp> = {
  originals: new RegExp(`^[0-9]{4}/(?:0[1-9]|1[0-2])/${ULID}\\.${EXT}$`),
  derived: new RegExp(`^${ULID}/(?:w[0-9]{2,4}|thumb)-[0-9a-f]{8}\\.webp$`),
  private: new RegExp(`^${ULID}/${ULID}\\.${EXT}$`),
  tmp: new RegExp(`^${ULID}(?:/(?:manifest\\.json|complete\\.lock|assembled|part-[1-9][0-9]?))?$`),
};

export const isValidKey = (area: Area, key: string): boolean => typeof key === "string" && key.length <= 255 && KEY_GRAMMAR[area].test(key);

type Env = Record<string, string | undefined>;

/**
 * The data directory from the environment: absolute, and never inside the application folder (the release) or a
 * `public` / `public_html` folder. Unset: a configuration error, raised only when media storage is actually used.
 */
export function dataDirFrom(env: Env = process.env, cwd: string = process.cwd()): string {
  const raw = env[DATA_DIR_ENV]?.trim();
  if (!raw) throw new StorageConfigError(`${DATA_DIR_ENV} is not set (media storage).`);
  if (!isAbsolute(raw)) throw new StorageConfigError(`${DATA_DIR_ENV} must be an absolute path.`);
  const dir = resolve(raw);
  const app = resolve(cwd);
  if (dir === app || dir.startsWith(app + sep)) throw new StorageConfigError(`${DATA_DIR_ENV} must be outside the application folder (it holds every upload).`);
  if (dir.split(sep).some((part) => part === "public" || part === "public_html")) {
    throw new StorageConfigError(`${DATA_DIR_ENV} must not be inside a public or public_html folder.`);
  }
  return dir;
}

/** One opened store: its real root and helpers that never leave it. */
export class MediaStore {
  readonly root: string;

  private constructor(root: string) {
    this.root = root;
  }

  /** Opens (and creates, 0700) the store at `dir`: its real path, symlinks resolved once. */
  static async open(dir: string): Promise<MediaStore> {
    await mkdir(dir, { recursive: true, mode: 0o700 });
    const real = await realpath(dir);
    const store = new MediaStore(real);
    for (const area of Object.keys(AREA_DIRS) as Area[]) await mkdir(store.areaRoot(area), { recursive: true, mode: 0o700 });
    return store;
  }

  areaRoot(area: Area): string {
    return join(this.root, AREA_DIRS[area]);
  }

  /**
   * The absolute path of a key in an area, after checking its grammar and that it resolves inside the area. It does not
   * touch the disk; `verifiedPath` also checks the real path of the directory holding it.
   */
  path(area: Area, key: string): string {
    if (!isValidKey(area, key)) throw new StoragePathError();
    const areaRoot = this.areaRoot(area);
    const full = resolve(areaRoot, key);
    const rel = relative(areaRoot, full);
    if (!rel || rel.startsWith("..") || isAbsolute(rel)) throw new StoragePathError();
    return full;
  }

  /**
   * Like `path`, and the real path of the directory that holds the key must still be inside the area's real root: a
   * directory replaced by a symlink to elsewhere is refused. (The file itself is opened with O_NOFOLLOW.)
   */
  async verifiedPath(area: Area, key: string): Promise<string> {
    const full = this.path(area, key);
    const parent = full.slice(0, full.lastIndexOf(sep));
    let realParent: string;
    let realArea: string;
    try {
      [realParent, realArea] = await Promise.all([realpath(parent), realpath(this.areaRoot(area))]);
    } catch {
      throw new StoragePathError("Storage location not found.");
    }
    if (realParent !== realArea && !realParent.startsWith(realArea + sep)) throw new StoragePathError();
    return full;
  }

  /** Creates the directory a key will live in (0700). */
  async ensureDirFor(area: Area, key: string): Promise<string> {
    const full = this.path(area, key);
    await mkdir(full.slice(0, full.lastIndexOf(sep)), { recursive: true, mode: 0o700 });
    return this.verifiedPath(area, key);
  }

  /** Opens a stored file for reading without following a symlink at its name; null when it does not exist. */
  async openRead(area: Area, key: string): Promise<{ handle: FileHandle; size: number } | null> {
    const full = await this.verifiedPath(area, key).catch((error) => {
      if (error instanceof StoragePathError && error.message === "Storage location not found.") return null;
      throw error;
    });
    if (!full) return null;
    let handle: FileHandle;
    try {
      handle = await open(full, constants.O_RDONLY | constants.O_NOFOLLOW);
    } catch (error) {
      const code = (error as NodeJS.ErrnoException).code;
      if (code === "ENOENT") return null;
      if (code === "ELOOP") throw new StoragePathError();
      throw error;
    }
    const info = await handle.stat();
    if (!info.isFile()) {
      await handle.close();
      throw new StoragePathError();
    }
    return { handle, size: info.size };
  }

  /** A read stream of a stored file (never through a symlink), or null when it does not exist. */
  async readStream(area: Area, key: string): Promise<{ stream: ReadStream; size: number } | null> {
    const opened = await this.openRead(area, key);
    if (!opened) return null;
    return { stream: opened.handle.createReadStream({ autoClose: true }), size: opened.size };
  }

  /**
   * Streams `source` into a key atomically (a temporary file beside it, then a rename), refusing more than `maxBytes`
   * and — when `exactBytes` is given — any other length. Returns the number of bytes written. A refused or broken stream
   * leaves nothing behind.
   */
  async writeStreamAtomic(area: Area, key: string, source: AsyncIterable<Uint8Array>, limits: { maxBytes: number; exactBytes?: number }): Promise<number> {
    const full = await this.ensureDirFor(area, key);
    const temp = `${full}.tmp-${randomBytes(6).toString("hex")}`;
    const handle = await open(temp, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW, 0o600);
    let written = 0;
    try {
      for await (const chunk of source) {
        written += chunk.byteLength;
        if (written > limits.maxBytes || (limits.exactBytes !== undefined && written > limits.exactBytes)) throw new StorageSizeError("too_large");
        await handle.write(chunk);
      }
      if (limits.exactBytes !== undefined && written !== limits.exactBytes) throw new StorageSizeError("wrong_size");
      await handle.sync();
    } catch (error) {
      await handle.close().catch(() => undefined);
      await unlink(temp).catch(() => undefined);
      throw error;
    }
    await handle.close();
    try {
      await rename(temp, full);
    } catch (error) {
      await unlink(temp).catch(() => undefined);
      throw error;
    }
    return written;
  }

  /** The size of a stored regular file (no symlinks), or null when it does not exist. */
  async sizeOf(area: Area, key: string): Promise<number | null> {
    const full = await this.verifiedPath(area, key).catch(() => null);
    if (!full) return null;
    try {
      const info = await lstat(full);
      return info.isFile() ? info.size : null;
    } catch {
      return null;
    }
  }

  /**
   * Writes bytes to a key atomically: a temporary file in the same directory (0600, exclusive create), flushed, then
   * renamed over the key. A reader never sees a partial file.
   */
  async writeAtomic(area: Area, key: string, data: Uint8Array): Promise<void> {
    const full = await this.ensureDirFor(area, key);
    const temp = `${full}.tmp-${randomBytes(6).toString("hex")}`;
    const handle = await open(temp, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW, 0o600);
    try {
      await handle.writeFile(data);
      await handle.sync();
    } finally {
      await handle.close();
    }
    try {
      await rename(temp, full);
    } catch (error) {
      await unlink(temp).catch(() => undefined);
      throw error;
    }
  }

  /** Moves a file between keys (same file system: an atomic rename), refusing to replace an existing target. */
  async move(fromArea: Area, fromKey: string, toArea: Area, toKey: string): Promise<void> {
    const from = await this.verifiedPath(fromArea, fromKey);
    const to = await this.ensureDirFor(toArea, toKey);
    const exists = await lstat(to).then(() => true, () => false);
    if (exists) throw new StoragePathError("The target already exists.");
    await rename(from, to);
  }

  /** Removes a stored file if it exists (no error when it does not). */
  async remove(area: Area, key: string): Promise<void> {
    const full = await this.verifiedPath(area, key).catch(() => null);
    if (full) await unlink(full).catch((error) => ((error as NodeJS.ErrnoException).code === "ENOENT" ? undefined : Promise.reject(error)));
  }

  /** Removes an upload's staging folder (its key is the upload's ULID). */
  async removeUpload(uploadId: string): Promise<void> {
    const full = this.path("tmp", uploadId);
    await rm(full, { recursive: true, force: true });
  }

  /** Every file under an area, as keys (relative, forward slashes); symlinks and other non-files are reported apart. */
  async listArea(area: Area): Promise<{ files: string[]; other: string[] }> {
    const root = this.areaRoot(area);
    const files: string[] = [];
    const other: string[] = [];
    const walk = async (dir: string, prefix: string, depth: number) => {
      if (depth > 4) return;
      let entries;
      try {
        entries = await readdir(dir, { withFileTypes: true });
      } catch {
        return;
      }
      for (const entry of entries) {
        const key = prefix ? `${prefix}/${entry.name}` : entry.name;
        if (entry.isDirectory()) await walk(join(dir, entry.name), key, depth + 1);
        else if (entry.isFile()) files.push(key);
        else other.push(key);
      }
    };
    await walk(root, "", 0);
    return { files: files.sort(), other: other.sort() };
  }

  /** Modification time of a path under an area (for the maintenance tool's age checks). */
  async modifiedAt(area: Area, key: string): Promise<Date | null> {
    try {
      return (await stat(this.path(area, key))).mtime;
    } catch {
      return null;
    }
  }
}

const HOLDER = Symbol.for("rawasy.media.store");

/** This process's store, opened on first use from RAWASY_DATA_DIR (never during a build). */
export async function mediaStore(env: Env = process.env): Promise<MediaStore> {
  if (process.env.NEXT_PHASE === "phase-production-build") throw new StorageConfigError("Media storage is not available while building.");
  const holder = globalThis as { [HOLDER]?: Promise<MediaStore> };
  holder[HOLDER] ??= MediaStore.open(dataDirFrom(env)).catch((error) => {
    delete holder[HOLDER];
    throw error;
  });
  return holder[HOLDER];
}

// --- Keys ----------------------------------------------------------------------------------------------------------------

export const originalKey = (fileId: string, extension: string, at: Date) =>
  `${at.getUTCFullYear()}/${String(at.getUTCMonth() + 1).padStart(2, "0")}/${fileId}.${extension}`;
export const privateKey = (mediaId: string, fileId: string, extension: string) => `${mediaId}/${fileId}.${extension}`;
export const derivedKey = (mediaId: string, variantKey: string, hash8: string) => `${mediaId}/${variantKey}-${hash8}.webp`;
/** The area of a stored original. */
export const areaOfFile = (storageArea: "originals" | "private") => storageArea;
